/**
 * Icon generator (zero-dependency). Turns every SVG in raw/icons/*.svg into a
 * typed React component in src/icons/<Name>.tsx, then writes the barrel
 * index.ts (named exports + `IconName` union + `icons` registry) and
 * assets.manifest.json (machine-readable index for agents).
 *
 * Solid fills (#hex / black / white) become `currentColor` so a single icon
 * adapts to light/dark via CSS `color`; gradients (`url(#...)`) and `none` are
 * preserved. Generated output is committed — re-run `pnpm run gen:icons` after
 * adding or changing a raw SVG. Do NOT hand-edit files under src/icons/.
 *
 * Usage: node scripts/gen-icons.mjs
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const rawDir = join(root, "raw", "icons");
const outDir = join(root, "src", "icons");
mkdirSync(outDir, { recursive: true });

const ATTR_RENAMES = {
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "clip-path": "clipPath",
  "stop-color": "stopColor",
  "stop-opacity": "stopOpacity",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "xlink:href": "xlinkHref",
  class: "className",
};

const pascal = (name) =>
  name
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");

function transform(svg) {
  let s = svg.trim();
  // Drop XML prolog / comments if present.
  s = s.replace(/<\?xml[^>]*\?>/g, "").replace(/<!--[\s\S]*?-->/g, "").trim();
  // Rename kebab/namespaced attributes to JSX (camelCase) form.
  for (const [from, to] of Object.entries(ATTR_RENAMES)) {
    s = s.replace(new RegExp(`(\\s)${from}=`, "g"), `$1${to}=`);
  }
  // Solid fills -> currentColor (leave none + url(#...) gradients untouched).
  s = s.replace(/fill="(#[0-9a-fA-F]{3,8}|black|white)"/g, 'fill="currentColor"');
  // Spread incoming props onto the root <svg> (last, so callers can override).
  s = s.replace(/<svg([^>]*)>/, "<svg$1 {...props}>");
  return s;
}

const files = readdirSync(rawDir).filter((f) => f.endsWith(".svg")).sort();
const names = [];

for (const file of files) {
  const base = file.replace(/\.svg$/, "");
  const comp = `${pascal(base)}Icon`;
  const jsx = transform(readFileSync(join(rawDir, file), "utf8"));
  const out = `// GENERATED by scripts/gen-icons.mjs from raw/icons/${file} — do not edit.
import type { SVGProps } from "react";

export const ${comp} = (props: SVGProps<SVGSVGElement>) => (
  ${jsx}
);
`;
  writeFileSync(join(outDir, `${comp}.tsx`), out);
  names.push({ key: base, comp });
}

// Barrel: named re-exports + IconName union + registry for <Icon name="..."> usage.
const index = `// GENERATED by scripts/gen-icons.mjs — do not edit.
import type { ReactElement, SVGProps } from "react";
${names.map((n) => `import { ${n.comp} } from "./${n.comp}";`).join("\n")}

${names.map((n) => `export { ${n.comp} } from "./${n.comp}";`).join("\n")}

export const iconNames = [${names.map((n) => `"${n.key}"`).join(", ")}] as const;
export type IconName = (typeof iconNames)[number];

export type IconComponent = (props: SVGProps<SVGSVGElement>) => ReactElement;

export const icons: Record<IconName, IconComponent> = {
${names.map((n) => `  "${n.key}": ${n.comp},`).join("\n")}
};
`;
writeFileSync(join(outDir, "index.ts"), index);

writeFileSync(
  join(root, "assets.manifest.json"),
  JSON.stringify(
    {
      generatedBy: "scripts/gen-icons.mjs",
      icons: names.map((n) => ({ name: n.key, component: n.comp, import: "@repo/assets/icons" })),
    },
    null,
    2,
  ) + "\n",
);

console.log(`gen-icons: wrote ${names.length} icon components -> src/icons/`);
