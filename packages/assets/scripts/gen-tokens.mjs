/**
 * Token CSS generator. Emits src/tokens/tokens.css (CSS custom properties +
 * prefers-color-scheme dark) from src/tokens/tokens.values.json, the single
 * source of truth. Apps `@import "@repo/assets/tokens.css"` in globals.css.
 * Generated output is committed — re-run `pnpm run gen:tokens` after editing
 * the JSON. Do NOT hand-edit tokens.css.
 *
 * Usage: node scripts/gen-tokens.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensDir = join(here, "..", "src", "tokens");
const values = JSON.parse(readFileSync(join(tokensDir, "tokens.values.json"), "utf8"));

const lightVars = Object.entries(values.color.light)
  .map(([k, v]) => `  --${k}: ${v};`)
  .join("\n");
const darkVars = Object.entries(values.color.dark)
  .map(([k, v]) => `    --${k}: ${v};`)
  .join("\n");
const fontVars = Object.entries(values.font)
  .map(([k, v]) => `  --font-${k}: ${v};`)
  .join("\n");

const css = `/* GENERATED by scripts/gen-tokens.mjs from src/tokens/tokens.values.json — do not edit. */
:root {
${lightVars}
${fontVars}
}

@media (prefers-color-scheme: dark) {
  :root {
${darkVars}
  }
}
`;

writeFileSync(join(tokensDir, "tokens.css"), css);
console.log("gen-tokens: wrote src/tokens/tokens.css");
